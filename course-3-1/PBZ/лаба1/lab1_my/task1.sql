DROP TABLE IF EXISTS отчёт CASCADE;
DROP TABLE IF EXISTS проекты;
DROP TABLE IF EXISTS детали;
DROP TABLE IF EXISTS поставщики;

CREATE TABLE поставщики (
    п_номер VARCHAR(10) PRIMARY KEY,
    имя_п VARCHAR(50),
    статус INT,
    город VARCHAR(50)
);

CREATE TABLE детали (
    д_номер VARCHAR(10) PRIMARY KEY,
    имя_д VARCHAR(50),
    цвет VARCHAR(50),
    размер INT,
    город VARCHAR(50)
);

CREATE TABLE проекты (
    пр_номер VARCHAR(10) PRIMARY KEY,
    имя_пр VARCHAR(50),
    город VARCHAR(50)
);

CREATE TABLE отчёт (
    п_номер VARCHAR(10),
    д_номер VARCHAR(10),
    пр_номер VARCHAR(10),
    количество INT,
    FOREIGN KEY (п_номер) REFERENCES поставщики(п_номер),
    FOREIGN KEY (д_номер) REFERENCES детали(д_номер),
    FOREIGN KEY (пр_номер) REFERENCES проекты(пр_номер)
);


