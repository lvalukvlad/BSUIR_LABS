-- 22. Получить номера проектов, использующих по крайней мере одну деталь, имеющуюся у поставщика П1.
SELECT DISTINCT пр_номер
FROM отчёт
WHERE д_номер IN (
    SELECT д_номер
    FROM отчёт
    WHERE п_номер = 'П1'
);

-- 21. Получить номера деталей, поставляемых для какого-либо проекта в Лондоне.
SELECT DISTINCT д_номер
FROM отчёт
JOIN проекты ON отчёт.пр_номер = проекты.пр_номер
WHERE проекты.город = 'Москва';

-- 29. Получить номера проектов, полностью обеспечиваемых поставщиком П1.
SELECT DISTINCT пр_номер
FROM проекты p
WHERE NOT EXISTS (
    SELECT DISTINCT д_номер 
    FROM отчёт 
    WHERE пр_номер = p.пр_номер
    EXCEPT
    SELECT DISTINCT д_номер 
    FROM отчёт 
    WHERE пр_номер = p.пр_номер AND п_номер = 'П1'
)
AND EXISTS (
    -- Проверяем, что П1 вообще поставляет что-то для проекта
    SELECT 1 
    FROM отчёт 
    WHERE пр_номер = p.пр_номер AND п_номер = 'П1'
);

-- 4. Получить все отправки, где количество находится в диапазоне от 300 до 750 включительно.
SELECT п_номер, д_номер, пр_номер, количество
FROM отчёт
WHERE количество BETWEEN 300 AND 750;

-- 7. Получить все такие тройки "номера поставщиков-номера деталей-номера проектов", для которых выводимые поставщик, деталь и проект не размещены в одном городе.
SELECT DISTINCT о.п_номер, о.д_номер, о.пр_номер
FROM отчёт о
JOIN поставщики п ON о.п_номер = п.п_номер
JOIN детали д ON о.д_номер = д.д_номер
JOIN проекты пр ON о.пр_номер = пр.пр_номер
WHERE п.город != д.город OR п.город != пр.город OR д.город != пр.город;

-- 11. Получить все пары названий городов, для которых поставщик из первого города обеспечивает проект во втором городе.
SELECT DISTINCT п.город AS город_поставщика, пр.город AS город_проекта
FROM отчёт о
JOIN поставщики п ON о.п_номер = п.п_номер
JOIN проекты пр ON о.пр_номер = пр.пр_номер;

-- 15. Получить общее число проектов, обеспечиваемых поставщиком П1.
SELECT COUNT(DISTINCT пр_номер) AS общее_число_проектов
FROM отчёт
WHERE п_номер = 'П1';

-- 33. Получить все города, в которых расположен по крайней мере один поставщик, одна деталь или один проект.
SELECT город FROM поставщики
UNION
SELECT город FROM детали
UNION
SELECT город FROM проекты;

-- 25. Получить номера проектов, город которых стоит первым в алфавитном списке городов.
SELECT пр_номер
FROM проекты
WHERE город = (SELECT MIN(город) FROM проекты);

-- 36. Получить все пары номеров поставщиков, скажем, Пx и Пy, такие, что оба эти поставщика поставляют в точности одно и то же множество деталей.
SELECT s1.п_номер AS Пx, s2.п_номер AS Пy
FROM поставщики s1
JOIN поставщики s2 ON s1.п_номер < s2.п_номер
WHERE NOT EXISTS (
    SELECT д_номер, пр_номер 
    FROM отчёт 
    WHERE п_номер = s1.п_номер
    EXCEPT
    SELECT д_номер, пр_номер 
    FROM отчёт 
    WHERE п_номер = s2.п_номер
)
AND NOT EXISTS (
    SELECT д_номер, пр_номер 
    FROM отчёт 
    WHERE п_номер = s2.п_номер
    EXCEPT
    SELECT д_номер, пр_номер 
    FROM отчёт 
    WHERE п_номер = s1.п_номер
);